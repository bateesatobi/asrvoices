export function getAdCreativeTemplate(id) {
  return AD_CREATIVE_TEMPLATES.find((t) => t.id === id) || null;
}

export function isVideoTemplate(template) {
  return template?.kind === 'video' || Boolean(template?.coverVideo);
}

export function countTemplatesInCategory(categoryId) {
  if (categoryId === 'all') return AD_CREATIVE_TEMPLATES.length;
  if (categoryId === 'short-video') {
    return AD_CREATIVE_TEMPLATES.filter((t) => t.kind === 'video').length;
  }
  return AD_CREATIVE_TEMPLATES.filter((t) => t.category === categoryId).length;
}
